"""
Capture Plotly's palettes into src/shared/palette.ts.

The Dash app shipped these to the browser in the `gl-palette` store rather
than re-typing them in JavaScript, so that the two renderers could not
disagree about a colour. There is one renderer now, so the values have to
live somewhere -- but they are still Plotly's, and still captured rather
than transcribed. Re-run this when the colormap list changes.
"""

import io
import json
import sys

import plotly.io as pio
from plotly import colors

sys.path.insert(0, ".")
from layouts.layout_constants import colorscales  # noqa: E402

palette = {
    "colorscales": {name: colors.get_colorscale(name) for name in colorscales},
    "colorway": list(pio.templates["plotly"].layout.colorway),
}

body = json.dumps(palette, indent=2)
header = '''// Plotly's palettes, captured rather than transcribed.
//
// Generated by `scripts/palette.py` -- do not edit by hand.
//
// The Dash app resolved these in Python and shipped them to the browser in a
// store, so that the Plotly renderer and the WebGL one could not disagree
// about what colour a point is. Only the WebGL renderer survives, but the 2D
// views in the analysis dock are still Plotly, and a category coloured one way
// in the scene and another in a histogram is the same bug. So the values are
// still Plotly's own, and still captured by a script.

export interface Palette {
  /** Continuous colormaps, keyed by the name the rail offers. */
  colorscales: Record<string, [number, string][]>
  /** Categorical colours, assigned in group order and wrapping. */
  colorway: string[]
}

export const PALETTE: Palette = '''

io.open("src/shared/palette.ts", "w", encoding="utf-8", newline="\n").write(
    header + body + "\n"
)
print("colorway:", palette["colorway"])
print("colorscales:", len(palette["colorscales"]))
